const assert=require('node:assert/strict');
const {index,filter,status}=require('../identity-evidence.js');
const data=require('../data/registry/parcels/1175/434.json');
const date='2026-10-23';
const idx=index(data,date);
const p=data.properties.find(p=>p.members.some(m=>m[4]==='75'));
assert.ok(p);
assert.ok(idx.byProperty.get(p.id).some(e=>e.entranceId==='40966'));
assert.ok(filter(data,idx,{query:'1175/434/75'}).some(x=>x.id===p.id));
assert.ok(filter(data,idx,{query:'L219/1175/434/75'}).some(x=>x.id===p.id));
const prefixFixture=JSON.parse(JSON.stringify(data));
prefixFixture.properties.push({...p,id:'test-sub750',members:[['L219','','1175','434','750']]});
assert.ok(!filter(prefixFixture,index(prefixFixture,date),{query:'1175/434/75'}).some(x=>x.id==='test-sub750'),'full key search must not match a longer subalterno');
assert.ok(filter(data,idx,{entrance:'40966'}).some(x=>x.id===p.id));
const grouped=filter(data,idx,{kind:'grouped'});
assert.ok(grouped.some(p=>p.members.length===2&&p.members.some(m=>m[4]==='8')&&p.members.some(m=>m[4]==='9')));
assert.equal(status({review:{decision:'accepted',valid_to:'2026-10-23'}},date),'outside_validity');
assert.equal(status({review:{decision:'accepted',valid_from:'2026-10-24'}},date),'outside_validity');
assert.equal(status({review:{decision:'rejected'}},date),'rejected');
assert.equal(status({review:{decision:'accepted'}},date),'accepted');
assert.equal(status({},date),'candidate');
const fixture=JSON.parse(JSON.stringify(data));
fixture.links.filter(l=>l.kind==='property_entrance'&&l.source===p.id).forEach(l=>l.review={decision:'rejected'});
const reviewed=index(fixture,date);
assert.ok(filter(fixture,reviewed,{kind:'unlinked'}).some(x=>x.id===p.id));
assert.ok(!filter(fixture,reviewed,{entrance:'40966'}).some(x=>x.id===p.id));
assert.ok(fixture.links.some(l=>l.source===p.id&&l.review?.decision==='rejected'),'rejected source evidence retained');
assert.equal(filter(data,idx,{}).length,data.properties.length);
assert.equal(filter(data,idx,{query:'this-is-not-an-address'}).length,0);
console.log('Identity filters verified: exact cadastral search, entrance links, grouped members, rejected-link retention, and exclusive review validity.');
